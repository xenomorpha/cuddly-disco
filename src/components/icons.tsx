export const BOARD_ICONS = [
  'board', 'home', 'flask', 'palette', 'folder', 'lock', 'bulb', 'book', 'rocket', 'target', 'leaf', 'mic',
  'calendar', 'star', 'compass', 'heart', 'cloud', 'coffee', 'pencil', 'puzzle', 'sparkle', 'planet', 'flag', 'music', 'database',
];

/** Older workspaces stored emoji as board icons; map them onto the icon set. */
const EMOJI_TO_ICON: Record<string, string> = {
  '📋': 'board', '🔬': 'flask', '🧪': 'flask', '🎨': 'palette', '🗂': 'folder', '📁': 'folder', '🔒': 'lock', '💡': 'bulb',
  '📚': 'book', '📖': 'book', '🚀': 'rocket', '🎯': 'target', '🌱': 'leaf', '🏠': 'home', '🎙': 'mic', '📅': 'calendar',
  '⭐': 'star', '1️⃣': 'flag', '📥': 'inbox', '📝': 'pencil',
};

export function normalizeIcon(icon: string | undefined): string {
  if (!icon) return 'board';
  if (ICONS[icon]) return icon;
  return EMOJI_TO_ICON[icon] ?? EMOJI_TO_ICON[icon.replace(/️/g, '')] ?? 'board';
}

export function Icon({ name, size = 18, className, title }: { name: string; size?: number; className?: string; title?: string }) {
  const spec = ICONS[name] ?? ICONS.note;
  return (
    <svg
      className={'icon ' + (className ?? '')}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title && <title>{title}</title>}
      {spec.f && <path d={spec.f} fill="currentColor" stroke="none" opacity={0.14} />}
      <path d={spec.s} />
    </svg>
  );
}

export function BoardIcon({ icon, size = 18 }: { icon?: string; size?: number }) {
  return <Icon name={normalizeIcon(icon)} size={size} className="board-glyph" />;
}

export function CardTypeIcon({ type, size = 16 }: { type: CardType | 'tag' | 'broken' | 'line'; size?: number }) {
  return <Icon name={type} size={size} />;
}

